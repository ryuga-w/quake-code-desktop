// `satisfies TranslationShape<typeof trMessages>` above makes missing or
// misspelled English keys a compile-time error instead of silently falling
// back to Turkish at runtime.
const messages = { tr: trMessages, en: enMessages } as const;

type Join<Key, Suffix> = Key extends string
  ? Suffix extends string
    ? `${Key}.${Suffix}`
    : never
  : never;
type DeepKey<T> = {
  [Key in keyof T & string]: T[Key] extends string
    ? Key
    : T[Key] extends Record<string, unknown>
      ? Join<Key, DeepKey<T[Key]>>
      : never;
}[keyof T & string];

export type TranslationKey = DeepKey<(typeof messages)["tr"]>;
export type Translate = (key: TranslationKey, values?: Record<string, string | number>) => string;

type I18nContextValue = {
  locale: AppLocale;
  preference: LocalePreference;
  setPreference: (next: LocalePreference) => void;
  t: Translate;
};

// Standalone component renders (storybook, SSR, and source-level tests) keep
// the established Turkish default even when the application provider is not
// mounted. The real app always overrides this value through I18nProvider.
const fallbackI18n: I18nContextValue = {
  locale: "tr",
  preference: "auto",
  setPreference: () => undefined,
  t: (key, values) => interpolate(readMessage("tr", key) ?? key, values),
};
const I18nContext = createContext<I18nContextValue>(fallbackI18n);

function normalizePreference(value: unknown): LocalePreference {
  return value === "tr" || value === "en" || value === "auto" ? value : "auto";
}

function readPreference(): LocalePreference {
  try {
    return normalizePreference(localStorage.getItem(LOCALE_STORAGE_KEY));
  } catch {
    return "auto";
  }
}

function resolveSystemLocale(): AppLocale {
  if (typeof navigator === "undefined") return "tr";
  const candidates = [...(navigator.languages || []), navigator.language].filter(Boolean);
  return candidates.some((candidate) => candidate.toLowerCase().startsWith("tr")) ? "tr" : "en";
}

function resolveLocale(preference: LocalePreference): AppLocale {
  return preference === "auto" ? resolveSystemLocale() : preference;
}

function readMessage(locale: AppLocale, key: TranslationKey): string | undefined {
  const value = key.split(".").reduce<unknown>((current, part) => {
    if (!current || typeof current !== "object") return undefined;
    return (current as Record<string, unknown>)[part];
  }, messages[locale]);
  return typeof value === "string" ? value : undefined;
}

function interpolate(message: string, values?: Record<string, string | number>): string {
  if (!values) return message;
  return message.replace(/\{(\w+)\}/g, (token, name) => String(values[name] ?? token));
}

export function localeForIntl(locale: AppLocale): string {
  return locale === "tr" ? "tr-TR" : "en-US";
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [preference, setPreferenceState] = useState<LocalePreference>(readPreference);
  const locale = resolveLocale(preference);

  useEffect(() => {
    try {
      localStorage.setItem(LOCALE_STORAGE_KEY, preference);
    } catch {
      // Storage is optional in restricted renderer contexts.
    }
    if (typeof document !== "undefined") {
      document.documentElement.lang = locale;
      document.documentElement.dataset.locale = locale;
    }
    desktop?.setNativeLocale?.(locale);
  }, [locale, preference]);

  const setPreference = useCallback((next: LocalePreference) => {
    setPreferenceState(normalizePreference(next));
  }, []);

  const t = useCallback<Translate>((key, values) => {
    const message = readMessage(locale, key) ?? readMessage("tr", key) ?? key;
    return interpolate(message, values);
  }, [locale]);

  const value = useMemo<I18nContextValue>(
    () => ({ locale, preference, setPreference, t }),
    [locale, preference, setPreference, t],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  return useContext(I18nContext);
}
